pluginManagement {
    val flutterSdkPath =
        run {
            val properties = java.util.Properties()
            val localProperties = file("local.properties")
            val fromFile =
                if (localProperties.exists()) {
                    localProperties.inputStream().use { properties.load(it) }
                    properties.getProperty("flutter.sdk")
                } else {
                    null
                }

            val fromEnv = System.getenv("FLUTTER_ROOT") ?: System.getenv("FLUTTER_HOME")

            val resolved = fromFile ?: fromEnv
            require(!resolved.isNullOrBlank()) {
                "Flutter SDK path not found. Set flutter.sdk in android/local.properties (generated by Flutter/Android Studio) or set FLUTTER_ROOT env var."
            }
            resolved
        }

    includeBuild("$flutterSdkPath/packages/flutter_tools/gradle")

    repositories {
        google()
        mavenCentral()
        gradlePluginPortal()
    }
}

